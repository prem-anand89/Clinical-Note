// FM review fixes: enabled flag, grid-missing strip, Mo/Ve phone fit. Run: node tests/fm-review3.mjs
import { createRequire } from 'module';
const require = createRequire('/home/theranet/TN Project/thera-net-1/package.json');
const { chromium } = require('playwright-core');
import path from 'path';
import { fileURLToPath } from 'url';
const dir = path.dirname(fileURLToPath(import.meta.url));
const results = []; const ok = (n, c, x) => { results.push([n, !!c]); console.log((c ? 'PASS ' : 'FAIL ') + n + (c ? '' : '  ' + JSON.stringify(x))); };
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true });
const page = await (await browser.newContext({ viewport: { width: 390, height: 900 } })).newPage();
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.goto('file://' + path.join(dir, '..', 'clinical-note.html'));
ok('FM not enabled on a fresh note', (await page.evaluate(() => window.getFmData().enabled)) === false);
await page.click('#region-chips [data-chip="Knee"]');
await page.waitForTimeout(200);
const d0 = await page.evaluate(() => window.getFmData());
ok('auto-routed row exists but enabled is false (consumers can ignore it)', d0.enabled === false && d0.segments.length === 1, d0.segments);
ok('cn.fm mirror stays empty when FM is not enabled', (await page.evaluate(() => JSON.parse(localStorage.getItem('cn.fm') || '[]').length)) === 0);
await page.evaluate(() => window.openAdvancedModule('fascial-manipulation'));
await page.waitForTimeout(500);
ok('enabled after opening FM', (await page.evaluate(() => window.getFmData().enabled)) === true);
ok('segment missing from the grid is offered', (await page.locator('#fm-grid-missing-chips').textContent()).includes('GE'));
ok('grid starts empty for the routed segment', (await page.locator('#fm-pv-table tbody tr').count()) === 0);
await page.locator('#fm-grid-missing-chips .chip').first().click();
await page.waitForTimeout(250);
ok('one tap adds it to the grid and the strip disappears', (await page.locator('#fm-pv-table tbody tr').count()) === 1 && !(await page.locator('#fm-grid-missing').isVisible()));
ok('no duplicate segment row created in Card 1', (await page.locator('#fm-seg-table tbody tr').count()) === 1);
const fit = await page.evaluate(() => { const w = document.getElementById('fm-move-table').parentElement; return [w.scrollWidth, w.clientWidth]; });
ok('Mo/Ve table fits at 390 px (no cropped Outcome column)', fit[0] <= fit[1], fit);
await page.evaluate(() => window.hideAdvancedModule('fascial-manipulation'));
await page.waitForTimeout(300);
ok('removing FM clears enabled and the cn.fm mirror', (await page.evaluate(() => window.getFmData().enabled)) === false && (await page.evaluate(() => JSON.parse(localStorage.getItem('cn.fm') || '[]').length)) === 0);
ok('no page errors', errors.length === 0, errors);
await browser.close();
const failed = results.filter(r => !r[1]).length;
console.log(failed ? failed + ' FAILED' : 'ALL PASS'); process.exit(failed ? 1 : 0);
